let x = 5;

console.log("Floor:", Math.floor(x));
console.log("Round:", Math.round(x));
console.log("Ceil:", Math.ceil(x));

console.log("Square Root:", Math.sqrt(x));
console.log("Power:", Math.pow(x, 2));
console.log("Absolute:", Math.abs(-x));
console.log("Maximum:", Math.max(5, 10, 15, 20));
console.log("Minimum:", Math.min(5, 10, 15, 20));
console.log("Random:", Math.random());

console.log("Cube:", Math.pow(x, 3));
console.log("Sign:", Math.sign(x));
console.log("Truncated:", Math.trunc(5.89));